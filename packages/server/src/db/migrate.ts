import type pg from 'pg';

interface Migration {
  id: string;
  sql: string;
}

// Migrations are append-only: never edit one that has been deployed, add a new
// one instead. They live in code (not .sql files) so the build output is
// self-contained and the Docker image needs nothing else copied in.
const MIGRATIONS: Migration[] = [
  {
    id: '001_canvases_and_strokes',
    sql: `
      CREATE TABLE canvases (
        id         text PRIMARY KEY,
        created_at timestamptz NOT NULL DEFAULT now()
      );

      CREATE TABLE strokes (
        -- Insertion order; strokes are replayed in this order.
        seq        bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
        -- Generated by the client, so a retried insert can be detected.
        id         uuid NOT NULL UNIQUE,
        canvas_id  text NOT NULL REFERENCES canvases (id) ON DELETE CASCADE,
        color      text NOT NULL,
        width      real NOT NULL,
        points     jsonb NOT NULL,
        created_at timestamptz NOT NULL DEFAULT now()
      );

      CREATE INDEX strokes_canvas_id_seq_idx ON strokes (canvas_id, seq);
    `,
  },
];

// Arbitrary constant shared by every instance of the server. Holding this
// advisory lock means two containers starting at once (e.g. during a rolling
// deploy) cannot apply the same migration twice.
const MIGRATION_LOCK_ID = 727_001;

export async function migrate(pool: pg.Pool): Promise<void> {
  const client = await pool.connect();
  try {
    await client.query('SELECT pg_advisory_lock($1)', [MIGRATION_LOCK_ID]);
    await client.query(`
      CREATE TABLE IF NOT EXISTS schema_migrations (
        id         text PRIMARY KEY,
        applied_at timestamptz NOT NULL DEFAULT now()
      )
    `);

    const { rows } = await client.query<{ id: string }>('SELECT id FROM schema_migrations');
    const applied = new Set(rows.map((r) => r.id));

    for (const migration of MIGRATIONS) {
      if (applied.has(migration.id)) continue;

      // Each migration and its bookkeeping row commit together, so a failure
      // leaves the schema exactly as it was before that migration.
      await client.query('BEGIN');
      try {
        await client.query(migration.sql);
        await client.query('INSERT INTO schema_migrations (id) VALUES ($1)', [migration.id]);
        await client.query('COMMIT');
      } catch (err) {
        await client.query('ROLLBACK');
        throw err;
      }
      console.log(`Applied migration ${migration.id}`);
    }
  } finally {
    // Session-level lock: releasing the connection would also free it, but
    // the pool keeps connections open, so unlock explicitly.
    await client.query('SELECT pg_advisory_unlock($1)', [MIGRATION_LOCK_ID]).catch(() => {});
    client.release();
  }
}
